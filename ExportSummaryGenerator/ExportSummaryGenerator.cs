using System;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace ExportSummaryGenerator;

// ===== 什么是源代码生成器？ =====
// 源代码生成器（Source Generator）是在编译过程中运行的一段程序。
// 它可以“阅读”你写的代码，再自动补写一些新代码，新代码会和你的代码一起编译。
// 它不会在游戏运行时执行；游戏运行时只会看到生成好的 DescribeExports() 方法。
//
// 本生成器的作用：
// 找到带 [GenerateExportSummary] 的类，为它生成一个 DescribeExports() 方法。
// 以 Scripts/ExportDemo.cs 为例，生成的代码大致如下：
//
//     partial class @ExportDemo
//     {
//         public string DescribeExports()
//         {
//             var result = new global::System.Text.StringBuilder();
//             result.Append("Health=").Append(this.@Health).AppendLine();
//             result.Append("DisplayName=").Append(this.@DisplayName).AppendLine();
//             return result.ToString();
//         }
//     }
//
// 小提示：这个项目使用 Roslyn（C# 编译器平台）提供的 API。
// 其中 Syntax（语法）指代码的文字结构，例如“这里有一个 class 声明”；
// Symbol（符号）指编译器理解后的含义，例如“这个类有哪些成员、成员上有哪些特性”。

// [Generator] 让编译器知道：这个类是一个源代码生成器，编译时需要加载并运行它。
// IIncrementalGenerator 是“增量生成器”接口：代码没有变化的部分可以复用上次的结果，
// 因此在编辑器里一边打字一边分析时更快。
[Generator]
public sealed class ExportSummaryGenerator : IIncrementalGenerator
{
    // 标记特性的“完整名称”：命名空间 + 类名。
    // 生成器靠这个字符串找到带 [GenerateExportSummary] 的类。
    // 它必须与下方 MarkerAttributeSource 中声明的命名空间和类名保持一致。
    private const string MarkerAttribute = "ExportDemo.GenerateExportSummaryAttribute";

    // 标记特性的源码，由生成器在编译开始时直接加入主项目，用户无需手写这个类。
    // 特性本身没有任何逻辑，只是一个记号；AttributeUsage 规定它的使用方式：
    // - AttributeTargets.Class：只能贴在类上，贴到方法或属性上会编译报错。
    // - Inherited = false：子类不会自动继承这个标签，需要汇总的类必须自己标注。
    // 声明为 internal：如果多个项目都引用了本生成器，各自生成的特性互不可见，不会产生类型冲突。
    // 使用时可以省略 Attribute 后缀，所以写 [GenerateExportSummary] 等同于写 [GenerateExportSummaryAttribute]。
    private const string MarkerAttributeSource = """
        // <auto-generated/>
        namespace ExportDemo;

        [global::System.AttributeUsage(global::System.AttributeTargets.Class, Inherited = false)]
        internal sealed class GenerateExportSummaryAttribute : global::System.Attribute
        {
        }
        """;

    // Godot 的 [Export] 特性的完整名称，用于判断某个成员是否被导出。
    private const string ExportAttribute = "Godot.ExportAttribute";

    // DiagnosticDescriptor 描述一种“编译诊断”，即编译器显示的错误或警告。
    // 当类不符合要求时，生成器会报出这个错误，它会出现在 IDE 的错误列表和构建输出中，
    // 就像普通的 C# 编译错误一样。参数依次为：
    // - "EGD001"：错误编号，方便搜索和识别。
    // - 标题：错误的简短说明。
    // - 消息格式：{0} 会被替换成出错的类名。
    // - "ExportSummary"：错误所属的分类。
    // - DiagnosticSeverity.Error：严重级别为“错误”，会导致编译失败。
    // - isEnabledByDefault: true：默认启用此诊断。
    private static readonly DiagnosticDescriptor UnsupportedClass = new(
        "EGD001",
        "Unsupported export summary class",
        "'{0}' must be a top-level, non-generic partial class",
        "ExportSummary",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    // Initialize 是生成器的入口，编译器加载生成器时会调用它。
    // 这里并不直接生成代码，而是“搭建流水线”：告诉编译器要关注哪些代码，以及找到后要做什么。
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        // 第零步：注入标记特性。
        // RegisterPostInitializationOutput 中添加的代码不依赖用户代码，会在分析用户代码之前加入编译，
        // 因此用户代码中的 [GenerateExportSummary] 能解析到这个类型，下面的 ForAttributeWithMetadataName 也能匹配到它。
        context.RegisterPostInitializationOutput(static postInitContext =>
            postInitContext.AddSource(
                "GenerateExportSummaryAttribute.g.cs",
                SourceText.From(MarkerAttributeSource, Encoding.UTF8)));

        // 第一步：筛选。按特性的完整元数据名查找，只有被标记的类才进入后续生成流程。
        // ForAttributeWithMetadataName 的三个参数：
        // 1. MarkerAttribute：要查找的特性名称。
        // 2. 快速过滤：只保留 class 声明（ClassDeclarationSyntax），跳过 struct、record 等其他声明。
        // 3. 转换：从匹配结果中取出类对应的“符号”（INamedTypeSymbol），后续用它查询类的成员。
        // 参数中的下划线 _ 表示“这个参数用不到”（这里是取消令牌 CancellationToken）。
        // static 修饰 lambda 表示它不捕获外部变量，可以避免意外地依赖外部状态。
        var classes = context.SyntaxProvider.ForAttributeWithMetadataName(
            MarkerAttribute,
            static (node, _) => node is ClassDeclarationSyntax,
            static (attributeContext, _) => (INamedTypeSymbol)attributeContext.TargetSymbol);

        // 第二步：输出。每找到一个被标记的类，就调用一次 Generate，为它生成代码。
        context.RegisterSourceOutput(classes, static (output, type) => Generate(output, type));
    }

    // 为一个被标记的类生成 DescribeExports() 方法。
    // context：用于报告错误和添加生成的源文件。
    // type：被标记的类的符号信息。
    private static void Generate(SourceProductionContext context, INamedTypeSymbol type)
    {
        // ----- 1. 检查类是否满足生成条件 -----

        // 一个 partial 类可能分散在多个文件中，DeclaringSyntaxReferences 包含它的所有声明位置。
        // 只要任一声明写了 partial 关键字，就认为它是 partial 类。
        // （如果一个类有多处声明，C# 要求它们都是 partial，否则编译器会另外报错。）
        bool isPartial = type.DeclaringSyntaxReferences.Any(reference =>
            reference.GetSyntax() is ClassDeclarationSyntax declaration &&
            declaration.Modifiers.Any(SyntaxKind.PartialKeyword));

        // 本生成器只支持简单情况，以下任一条件不满足就报错并跳过：
        // - !isPartial：不是 partial 类，生成的代码无法与原类合并。
        // - type.ContainingType is not null：这是嵌套类（写在另一个类里面），
        //   生成嵌套类需要同时生成外层类的声明，这里没有实现。
        // - type.TypeParameters.Length != 0：这是泛型类（如 MyNode<T>），这里同样没有实现。
        if (!isPartial || type.ContainingType is not null || type.TypeParameters.Length != 0)
        {
            // type.Locations.FirstOrDefault() 指出错误位置，IDE 会在该类名上画红色波浪线。
            context.ReportDiagnostic(Diagnostic.Create(UnsupportedClass, type.Locations.FirstOrDefault(), type.Name));
            return;
        }

        // ----- 2. 用 StringBuilder 拼接生成的 C# 源码文本 -----
        // 生成器的本质就是“拼字符串”：拼出一段合法的 C# 代码，再交给编译器编译。

        // 文件头：
        // - // <auto-generated/>：告诉 IDE 和代码分析工具这是自动生成的文件，不要对它报风格警告。
        // - #nullable enable：在生成的文件中启用可空引用类型检查，与主项目设置保持一致。
        var source = new StringBuilder("// <auto-generated/>\n#nullable enable\n");

        // 生成的类必须和原类位于同一个命名空间，partial 的两部分才能合并。
        // 如果原类没有写命名空间（位于“全局命名空间”），就不输出 namespace 语句。
        if (!type.ContainingNamespace.IsGlobalNamespace)
        {
            source.Append("namespace ").Append(type.ContainingNamespace.ToDisplayString()).AppendLine(";");
        }

        // 输出类声明和方法开头。
        // 类名前的 @ 是 C# 的“逐字标识符”写法，允许名字与关键字相同（例如 @class）。
        // 即使类名恰好是 C# 关键字，生成的代码也能编译。
        // global::System.Text.StringBuilder 写完整名称，是为了避免与用户项目中同名的类型冲突。
        source.Append("partial class @").Append(type.Name).AppendLine()
            .AppendLine("{")
            .AppendLine("    public string DescribeExports()")
            .AppendLine("    {")
            .AppendLine("        var result = new global::System.Text.StringBuilder();");

        // ----- 3. 遍历类的成员，为每个导出成员生成一行拼接代码 -----
        // 只汇总当前类自身的导出实例成员；属性须可读，索引器不参与。
        // 注意：GetMembers() 只返回这个类自己声明的成员，不包括从父类继承的成员。
        foreach (var member in type.GetMembers())
        {
            // 条件一：跳过静态成员，以及没有 [Export] 特性的成员。
            // ToDisplayString() 返回特性类的完整名称，例如 "Godot.ExportAttribute"。
            // ?. 是空条件运算符：如果 AttributeClass 为 null（例如特性类型无法解析），结果也是 null，不会抛异常。
            if (member.IsStatic || !member.GetAttributes().Any(attribute =>
                    attribute.AttributeClass?.ToDisplayString() == ExportAttribute))
            {
                continue;
            }

            // 条件二：只保留可以读取值的字段或属性，其余成员（例如方法）一律跳过。
            // 这里使用 C# 的“属性模式”匹配：
            // - IFieldSymbol { IsImplicitlyDeclared: false }：手写的字段。
            //   编译器自动生成的字段（例如自动属性背后的存储字段）的 IsImplicitlyDeclared 为 true，会被排除。
            // - IPropertySymbol { IsIndexer: false, GetMethod: not null }：
            //   不是索引器（this[int i] 这种需要参数才能读取的属性），并且有 get 访问器（可以读取）。
            if (member is not IFieldSymbol { IsImplicitlyDeclared: false } &&
                member is not IPropertySymbol { IsIndexer: false, GetMethod: not null })
            {
                continue;
            }

            // 生成形如下面这一行代码：
            //     result.Append("Health=").Append(this.@Health).AppendLine();
            //
            // 转义成员名以生成合法字符串字面量；实际值在 DescribeExports() 调用时读取。
            // SymbolDisplay.FormatLiteral 会把文本变成带引号的 C# 字符串字面量，并处理需要转义的字符。
            // this.@成员名 是在读取成员的当前值：生成器只决定“读哪个成员”，
            // 具体是什么值要等游戏运行、调用 DescribeExports() 时才知道。
            source.Append("        result.Append(")
                .Append(Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(member.Name + "=", quote: true))
                .Append(").Append(this.@")
                .Append(member.Name)
                .AppendLine(").AppendLine();");
        }

        // 输出方法结尾和类结尾。
        source.AppendLine("        return result.ToString();")
            .AppendLine("    }")
            .AppendLine("}");

        // ----- 4. 把生成的源码交给编译器 -----

        // hintName 是生成文件的名字，同一个生成器产生的文件名不能重复。
        // FullyQualifiedFormat 会得到类似 "global::ExportDemo.ExportDemo" 的完整名称（命名空间 + 类名），
        // 去掉 "global::" 后再加上后缀，最终文件名为 "ExportDemo.ExportDemo.ExportSummary.g.cs"。
        // 使用完整名称可以避免不同命名空间中的同名类产生相同的文件名。
        // 按惯例，.g.cs 后缀表示“生成的（generated）C# 文件”。
        var hintName = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)
            .Replace("global::", "") + ".ExportSummary.g.cs";

        // AddSource 把生成的代码加入本次编译，它会和你手写的代码一起被编译成程序集。
        context.AddSource(hintName, SourceText.From(source.ToString(), Encoding.UTF8));
    }
}
